CAMPOS = ['Titulo', 'Dato curioso', 'Fuente dato'] + [f'{c} {i}' for i in (1, 2, 3) for c in ('Desarrollo', 'Problematica', 'Solucion')]

path = sys.argv[1]
wb = openpyxl.load_workbook(path)
t = wb['Temas Macro 2027']; h = [c.value for c in t[1]]
for s, dia, nuevo, puntos, motivo in V:
    t.cell(s + 1, h.index('Versiculo ' + dia) + 1).value = nuevo
    if puntos:
        t.cell(s + 1, h.index('3 Puntos ' + dia) + 1).value = puntos
g = wb['Guiones 2027']; hg = [c.value for c in g[1]]
filas = {(r[0].value, r[1].value): r for r in g.iter_rows(min_row=2) if r[0].value}
for k, vals in G.items():
    fila = filas[k]
    for campo, v in zip(CAMPOS, vals):
        if v is not None:
            fila[hg.index(campo)].value = v
wb.save(path)
print(len(V), 'versículos aplicados ·', len(G), 'guiones reescritos')
